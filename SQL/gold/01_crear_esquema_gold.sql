use GoldFiscal;
if not exists(
	select 1
	from sys.schemas
	where name='gold'
	)
begin
	exec('CREATE SCHEMA gold');
end;

IF OBJECT_ID('gold.UBICACION', 'U') IS NOT NULL DROP TABLE gold.UBICACION;
CREATE TABLE gold.UBICACION(
	PREFIJO_UBIGEO VARCHAR(4) NOT NULL PRIMARY KEY,
	NOMBRE_DEPARTAMENTO VARCHAR(50) NOT NULL,
	NOMBRE_PROVINCIA VARCHAR(50) NOT NULL,
	MACRO_REGION VARCHAR(20) NOT NULL);

IF OBJECT_ID('gold.RUBRO', 'U') IS NOT NULL DROP TABLE gold.RUBRO;
CREATE TABLE gold.RUBRO (
    RUBRO_NOMBRE            VARCHAR(100) NOT NULL PRIMARY KEY,
    CATEGORIA               VARCHAR(30)  NOT NULL,
    ES_NUMERADOR_AUTONOMIA  BIT          NOT NULL,
    ENTRA_EN_DENOMINADOR    BIT          NOT NULL
);


