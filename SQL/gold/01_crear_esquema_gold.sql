INSERT INTO gold.UBICACION (PREFIJO_UBIGEO, NOMBRE_DEPARTAMENTO, NOMBRE_PROVINCIA, MACRO_REGION)
SELECT DISTINCT
    LEFT(UBIGEO, 4),
    DEPARTAMENTO_EJECUTORA_NOMBRE,
    PROVINCIA_EJECUTORA_NOMBRE,
    'PENDIENTE'
FROM silver.ingreso;

UPDATE gold.UBICACION
SET MACRO_REGION =
    CASE
        WHEN PREFIJO_UBIGEO = '1501' THEN 'Lima Metropolitana'
        WHEN PREFIJO_UBIGEO = '0701' THEN 'Lima Metropolitana'
        WHEN LEFT(PREFIJO_UBIGEO, 2) = '15' THEN 'Lima Provincias'
        WHEN LEFT(PREFIJO_UBIGEO, 2) IN ('24','20','14','13','06','02') THEN 'Norte'
        WHEN LEFT(PREFIJO_UBIGEO, 2) IN ('11','10','19','12','09')      THEN 'Centro'
        WHEN LEFT(PREFIJO_UBIGEO, 2) IN ('04','05','03','08','21','18','23') THEN 'Sur'
        WHEN LEFT(PREFIJO_UBIGEO, 2) IN ('16','22','01','25','17')      THEN 'Oriente'
    END;
