-- a mano aca: cargar_silver.py reemplaza el marcador de columnas P23
-- (mas abajo, dentro del CREATE TABLE) en tiempo de ejecucion, leyendo
-- los nombres reales del Parquet de renamu (mismo criterio que
-- Src/silver/construir_renamu.py: prefijo "P23_"), para que la tabla
-- nunca se desincronice del dato real y para no tipear 90 lineas casi
-- identicas a mano.
