    P19D_NM INT NULL,
    P19D_NH INT NULL,
    P19D_CM INT NULL,
    P19D_CH INT NULL,
    P19D_LM INT NULL,
    P19D_LH INT NULL,
    P19D_VM INT NULL,
    P19D_VH INT NULL,
    P19_1_T INT NULL,
    P19_2_T INT NULL,
    P19_3_T INT NULL,
    P19_4_T INT NULL,
    P19_5_T INT NULL,
    P19_6_T INT NULL,
    {{COLUMNAS_P23}}
